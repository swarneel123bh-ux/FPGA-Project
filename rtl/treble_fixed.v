`timescale 1ns/1ps
// treble_fixed: goal 2 stage 1, fixed-rule treble restoration for 32 kbit/s MP3 (fc = 9 kHz since 12 Nov; was 7.2 kHz).
//
// WRITTEN BY CLAUDE (Swarneel's agent) on 11 Nov 2026, at Swarneel's request: Swarneel assigned
// this RTL port to Claude while the team brings up ANC. The port list is Swarneel's (from the
// earlier skeleton); the body is Claude's. Not written by a team member.
//
// Bit-exact with model/goal2/ref_fixed.py (read its header for the number formats):
//
//   x -> band-pass fc/2..fc (sections 0-3) -> |.| -> high-pass fc (4-7) -> sections 8-11
//     -> enh;   enh >>>= 2 if att12;   music = enh_en ? sat24(x + enh) : x
//
// [12 Nov] Two coefficient sets in the ROM (120 words), chosen per sample by tune_sel (SW6):
//   0 = original tuning (fc 7.2 kHz, low-pass 20 kHz in 8-11, gain 1)
//   1 = retune (fc 9 kHz, low-pass in 8-10, high-shelf EQ x -8 dB in 11)
// att12 (SW5) shifts the added treble right by 2 (-12 dB). Both are synchronised like enh_en and
// sampled at the start of each run. The two sets share one filter state (see ref_fixed.py).
//
// Each section is Direct Form I:  y = sat32((b0*x0 + b1*x1 + b2*x2 - a1*y1 - a2*y2 + 2^21) >>> 22)
// Samples inside are 32 bits (s24 << 4: 4 guard bits above, 4 fraction bits below).
// Coefficients are Q2.22, 25 bits, from rtl/treble_coefs.mem (generated by ref_fixed.py; never
// edit it by hand). ROM order per section: b0, b1, b2, -a1, -a2.
//
// Timing: one multiplier, used 5 times per section. Per section: 5 issue cycles, 2 pipeline
// drain cycles, 1 round/saturate cycle, 1 write-back cycle = 9 cycles; 12 sections = 108
// cycles, plus the start delay and one output cycle. The rounding is split over separate
// cycles (S_RND, S_WB, S_OUT) because in one cycle it was 12 ns, over the 10 ns clock.
// That is far inside the 2,083 cycles between ticks. The multiplier has registered inputs and a
// registered output so Vivado can map it onto DSP48E1 slices at 100 MHz.
//
// music_raw from music_fifo is valid 2 clocks after sample_tick (RAM read, then output register),
// so the run starts START_DELAY = 2 clocks after the tick. music changes about 100 clocks after
// the tick and holds until the next result; i2s_tx takes it on the next tick.
//
// enh_en is a slide switch: it goes through a 2-flop synchroniser. The filters run whatever
// enh_en is, so switching back to "enhanced" does not click from stale filter state.

module treble_fixed #(
	parameter COEF_FILE   = "treble_coefs.mem",
	parameter START_DELAY = 2						// clocks from sample_tick to valid music_raw
)(
	input wire clk,													// 100 MHz clk
	input wire rst,													// Active high sync reset
	input wire sample_tick,									// one-cycle tick signal
	input wire signed [23:0] music_raw,			// from music_fifo.v, valid START_DELAY clocks after the tick
	output reg signed [23:0] music,					// to out_mux, held until the next result
	input wire enh_en,											// 1 = enhanced, 0 = plain (switch)
	input wire tune_sel,										// [12 Nov] 0 = original tuning, 1 = retune (switch)
	input wire att12												// [12 Nov] 1 = added treble -12 dB (switch)
);

localparam N_SECT    = 12;							// sections per tuning
localparam N_TUNE    = 2;
localparam ABS_AFTER = 3;							// |.| on the output of section 3
localparam DATA_W    = 32;
localparam DATA_FRAC = 4;
localparam COEF_W    = 25;
localparam COEF_FRAC = 22;
localparam PROD_W    = DATA_W + COEF_W;		// 57
localparam ACC_W     = PROD_W + 3;				// 60: room for the sum of 5 products

localparam signed [DATA_W-1:0] D_MAX = {1'b0, {(DATA_W-1){1'b1}}};
localparam signed [DATA_W-1:0] D_MIN = {1'b1, {(DATA_W-1){1'b0}}};

// ---------------------------------------------------------------- coefficient ROM
(* rom_style = "distributed" *)
reg signed [COEF_W-1:0] coef [0:N_TUNE*N_SECT*5-1];
initial $readmemh(COEF_FILE, coef);

// ---------------------------------------------------------------- filter state, per section
reg signed [DATA_W-1:0] x1 [0:N_SECT-1];
reg signed [DATA_W-1:0] x2 [0:N_SECT-1];
reg signed [DATA_W-1:0] y1 [0:N_SECT-1];
reg signed [DATA_W-1:0] y2 [0:N_SECT-1];

// ---------------------------------------------------------------- switch synchronisers
reg enh_s1, enh_s2;
reg tune_s1, tune_s2, att_s1, att_s2;
always @(posedge clk) begin
	enh_s1  <= enh_en;
	enh_s2  <= enh_s1;
	tune_s1 <= tune_sel;
	tune_s2 <= tune_s1;
	att_s1  <= att12;
	att_s2  <= att_s1;
end

// ---------------------------------------------------------------- start delay after the tick
reg [START_DELAY:0] tick_dly;
wire start = tick_dly[START_DELAY];
always @(posedge clk) begin
	if (rst) tick_dly <= 0;
	else     tick_dly <= {tick_dly[START_DELAY-1:0], sample_tick};
end

// ---------------------------------------------------------------- sequencer
localparam S_IDLE  = 3'd0;
localparam S_ISSUE = 3'd1;
localparam S_DRAIN = 3'd2;
localparam S_RND   = 3'd3;							// round + saturate the accumulator into y_r
localparam S_WB    = 3'd4;							// update section state, next section input
localparam S_OUT   = 3'd5;							// final sum, saturate, write music

reg [2:0] state;
reg [3:0] sect;										// 0..11
reg [2:0] tap;										// 0..4: b0 x0, b1 x1, b2 x2, -a1 y1, -a2 y2
reg [6:0] cidx;										// coefficient address, tune*60 + sect*5 + tap
reg       att_l;										// att12, held for the whole run
reg       drain;
reg signed [23:0]       x_lat;				// the sample being processed
reg signed [DATA_W-1:0] v_in;					// input of the current section
reg signed [DATA_W-1:0] y_r;						// section output, rounded and saturated
reg signed [DATA_W-DATA_FRAC:0] enh_r;			// added treble, s24 LSB, 29 bits

// multiplier pipeline
reg signed [DATA_W-1:0] op_a;
reg signed [COEF_W-1:0] op_b;
reg                     op_v;
reg signed [PROD_W-1:0] prod;
reg                     prod_v;
reg signed [ACC_W-1:0]  acc;

reg signed [DATA_W-1:0] operand;
always @(*) begin
	case (tap)
		3'd0:    operand = v_in;
		3'd1:    operand = x1[sect];
		3'd2:    operand = x2[sect];
		3'd3:    operand = y1[sect];
		default: operand = y2[sect];
	endcase
end

// write-back arithmetic: y_sat is registered in S_RND, the rest uses y_r or enh_r
wire signed [ACC_W-1:0] acc_rnd = (acc + (1 <<< (COEF_FRAC-1))) >>> COEF_FRAC;
wire signed [DATA_W-1:0] y_sat =
	(acc_rnd > D_MAX) ? D_MAX :
	(acc_rnd < D_MIN) ? D_MIN : acc_rnd[DATA_W-1:0];
wire signed [DATA_W-1:0] y_abs =						// |y|, with |-2^31| saturated to 2^31-1
	(y_r == D_MIN) ? D_MAX : (y_r < 0) ? -y_r : y_r;
// Back to the s24 LSB, rounded. One extra bit so y_sat = 2^31-1 plus the rounding constant
// does not wrap (the Python model has unbounded integers).
wire signed [DATA_W:0]             y_ext = y_r;
wire signed [DATA_W:0]             enh_w = (y_ext + (1 <<< (DATA_FRAC-1))) >>> DATA_FRAC;
wire signed [DATA_W-DATA_FRAC:0]   enh   = enh_w[DATA_W-DATA_FRAC:0];	// 29 bits, fits
wire signed [DATA_W-DATA_FRAC+1:0] sum   = x_lat + enh_r;					// 30 bits, cannot overflow
localparam signed [DATA_W-DATA_FRAC+1:0] OUT_MAX =  (1 <<< 23) - 1;
localparam signed [DATA_W-DATA_FRAC+1:0] OUT_MIN = -(1 <<< 23);
wire signed [23:0] sum_sat =
	(sum > OUT_MAX) ? 24'sh7FFFFF :
	(sum < OUT_MIN) ? 24'sh800000 : sum[23:0];

integer i;
always @(posedge clk) begin
	if (rst) begin
		state  <= S_IDLE;
		sect   <= 0;
		tap    <= 0;
		cidx   <= 0;
		att_l  <= 0;
		drain  <= 0;
		x_lat  <= 0;
		v_in   <= 0;
		y_r    <= 0;
		enh_r  <= 0;
		op_a   <= 0;
		op_b   <= 0;
		op_v   <= 0;
		prod   <= 0;
		prod_v <= 0;
		acc    <= 0;
		music  <= 0;
		for (i = 0; i < N_SECT; i = i + 1) begin
			x1[i] <= 0; x2[i] <= 0; y1[i] <= 0; y2[i] <= 0;
		end
	end else begin
		// multiplier pipeline: operands -> product -> accumulate
		op_v   <= 1'b0;
		prod   <= op_a * op_b;
		prod_v <= op_v;
		if (prod_v) acc <= acc + prod;

		case (state)
			S_IDLE: begin
				// A tick that arrives mid-run cannot happen (run is ~100 of 2,083 clocks); it
				// would be ignored rather than corrupt the state.
				if (start) begin
					x_lat <= music_raw;
					v_in  <= {{(DATA_W-DATA_FRAC-24){music_raw[23]}}, music_raw, {DATA_FRAC{1'b0}}};
					sect  <= 0;
					tap   <= 0;
					cidx  <= tune_s2 ? N_SECT*5 : 0;	// tuning chosen once per sample
					att_l <= att_s2;
					acc   <= 0;
					state <= S_ISSUE;
				end
			end

			S_ISSUE: begin
				op_a <= operand;
				op_b <= coef[cidx];
				op_v <= 1'b1;
				cidx <= cidx + 1'b1;
				if (tap == 3'd4) begin
					tap   <= 0;
					drain <= 0;
					state <= S_DRAIN;
				end else begin
					tap <= tap + 1'b1;
				end
			end

			S_DRAIN: begin								// last product, then last accumulate
				drain <= 1'b1;
				if (drain) state <= S_RND;
			end

			S_RND: begin
				y_r   <= y_sat;
				acc   <= 0;								// prod_v is 0 here, so no add is lost
				state <= S_WB;
			end

			S_WB: begin
				x2[sect] <= x1[sect];
				x1[sect] <= v_in;
				y2[sect] <= y1[sect];
				y1[sect] <= y_r;
				if (sect == N_SECT-1) begin
					enh_r <= att_l ? (enh >>> 2) : enh;
					state <= S_OUT;
				end else begin
					v_in  <= (sect == ABS_AFTER) ? y_abs : y_r;
					sect  <= sect + 1'b1;
					state <= S_ISSUE;
				end
			end

			S_OUT: begin
				music <= enh_s2 ? sum_sat : x_lat;
				state <= S_IDLE;
			end

			default: state <= S_IDLE;
		endcase
	end
end

endmodule
